import type { SupabaseClient } from '@supabase/supabase-js';
import { describeAuthError, type AuthIssue } from './authMessages';

/**
 * Handles the branded return trip from emails and Google. Email links carry a
 * `token_hash` to GAYZE's own domain (see docs/AUTHENTICATION_AND_DOMAIN_SETUP.md),
 * which is exchanged here, so the link never has to show the Supabase hostname.
 * Errors that providers put in the URL are turned into friendly states, and the
 * URL is cleaned so tokens and codes do not stay in the address bar or history.
 */
export type CallbackResult =
  | { kind: 'none' }
  | { kind: 'recovery' }
  | { kind: 'verified' }
  | { kind: 'email_changed' }
  | { kind: 'error'; issue: AuthIssue; flow: 'recovery' | 'signup' | 'oauth' | 'other' };

export const AUTH_PATHS = ['/auth/confirm', '/auth/reset-password', '/auth/email-change', '/auth/magic-link'];
const OTP_TYPES = new Set(['signup', 'recovery', 'email_change', 'email', 'invite', 'magiclink']);

interface LocationLike { pathname: string; search: string; hash: string }

export function readCallbackParams(loc: LocationLike) {
  const query = new URLSearchParams(loc.search);
  const hash = new URLSearchParams(loc.hash.replace(/^#/, ''));
  const get = (k: string) => query.get(k) ?? hash.get(k);
  return {
    tokenHash: get('token_hash'),
    type: get('type'),
    code: query.get('code'),
    error: get('error'),
    errorCode: get('error_code'),
    errorDescription: get('error_description'),
    hasRecoveryHint: loc.pathname === '/auth/reset-password' || get('type') === 'recovery',
  };
}

export async function consumeAuthCallback(
  client: Pick<SupabaseClient, 'auth'>,
  loc: LocationLike,
  clean: (path: string) => void = (path) => window.history.replaceState({}, '', path),
): Promise<CallbackResult> {
  const p = readCallbackParams(loc);
  const onAuthPath = AUTH_PATHS.includes(loc.pathname);
  const hasSomething = p.tokenHash || p.error || p.code || onAuthPath;
  if (!hasSomething) return { kind: 'none' };

  const flow: 'recovery' | 'signup' | 'oauth' | 'other' =
    p.hasRecoveryHint ? 'recovery' : loc.pathname === '/auth/confirm' ? 'signup' : p.code || p.error ? 'oauth' : 'other';

  // Provider reported a problem in the URL (expired link, cancelled Google consent, ...).
  if (p.error || p.errorCode) {
    clean(flow === 'recovery' ? '/auth/reset-password' : '/');
    const issue = describeAuthError({ message: `${p.errorCode ?? ''} ${p.error ?? ''} ${p.errorDescription ?? ''}` }, flow === 'recovery' ? 'reset' : flow === 'oauth' ? 'oauth' : 'signup');
    return { kind: 'error', issue, flow };
  }

  if (p.tokenHash) {
    const type = p.type && OTP_TYPES.has(p.type) ? p.type : loc.pathname === '/auth/reset-password' ? 'recovery' : 'signup';
    const { error } = await client.auth.verifyOtp({ token_hash: p.tokenHash, type: type as 'signup' | 'recovery' | 'email_change' | 'email' | 'invite' | 'magiclink' });
    clean(type === 'recovery' ? '/auth/reset-password' : '/');
    if (error) return { kind: 'error', issue: describeAuthError(error, type === 'recovery' ? 'reset' : 'signup'), flow: type === 'recovery' ? 'recovery' : 'signup' };
    if (type === 'recovery') return { kind: 'recovery' };
    if (type === 'email_change') return { kind: 'email_changed' };
    return { kind: 'verified' };
  }

  // PKCE code flow (Google, and links generated by supabase-js): exchanged by the client itself
  // because detectSessionInUrl is on; here we only report the intent so the UI can respond.
  if (p.hasRecoveryHint) return { kind: 'recovery' };
  return { kind: 'none' };
}

let once: Promise<CallbackResult> | null = null;
/**
 * The callback URL can only be consumed once (tokens are single use and the URL is
 * cleaned). React may run an effect twice, so every caller shares the first result.
 */
export function consumeAuthCallbackOnce(client: Pick<SupabaseClient, 'auth'>, loc: LocationLike): Promise<CallbackResult> {
  if (!once) once = consumeAuthCallback(client, loc);
  return once;
}
